public class ContohTipeData11 {
    public static void main(String[] args) {
        char golonganDarah = 'B';
        byte jarak = (byte) 130;
        short jumlahPenduduk = 1025;
        float suhu = 36.5f;
        double beratBadan = 0.5467812345;
        long saldo = 150000000;
        int angkaDesimal = 0x10;
        System.out.println("Golongan Darah: " + (byte) golonganDarah);
        System.out.println("Jarak: " + jarak);
        System.out.println("Jumlah Penduduk: " + jumlahPenduduk);
        System.out.println("Suhu: " + suhu);
        System.out.println("Berat Badan: " + (float) beratBadan);
        System.out.println("Saldo: " + saldo);
        System.out.println("Angka Desimal: " + angkaDesimal);
    }
        
}
